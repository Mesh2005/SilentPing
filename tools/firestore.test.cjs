const {test, before, after} = require('node:test');
const fs = require('node:fs');
const {initializeTestEnvironment, assertSucceeds, assertFails} = require('@firebase/rules-unit-testing');
const {doc, setDoc, getDoc, getDocs, collection, query, where, updateDoc, serverTimestamp, deleteDoc} = require('firebase/firestore');
let env;
before(async () => {
  env = await initializeTestEnvironment({projectId: 'demo-silentping', firestore: {
    rules: fs.readFileSync(require('node:path').join(__dirname, '..', 'firestore.rules'), 'utf8'), host: '127.0.0.1', port: 8080,
  }});
});
after(async () => { await env?.cleanup(); });
test('private invitations, mutual consent, identity, cooldown and revocation', async () => {
  const owner = env.authenticatedContext('owner').firestore();
  const guest = env.authenticatedContext('guest').firestore();
  const outsider = env.authenticatedContext('outsider').firestore();
  const anon = env.unauthenticatedContext().firestore();
  const id = '1234567890abcdef1234567890abcdef';
  const room = db => doc(db, 'circles', id);
  const signal = (db, uid) => doc(db, 'circles', id, 'signals', uid);
  const ping = () => ({kind: 'ambient', sentAt: serverTimestamp()});
  await assertFails(setDoc(room(anon), {ownerUid: 'owner', guestUid: '', memberIds: ['owner'], status: 'waiting', createdAt: serverTimestamp()}));
  await assertSucceeds(setDoc(room(owner), {ownerUid: 'owner', guestUid: '', memberIds: ['owner'], status: 'waiting', createdAt: serverTimestamp()}));
  await assertFails(getDocs(collection(outsider, 'circles')));
  await assertSucceeds(getDoc(room(guest)));
  await assertFails(setDoc(signal(owner, 'owner'), ping()));
  await assertFails(updateDoc(room(guest), {guestUid: 'guest', memberIds: ['owner','guest'], status: 'connected'}));
  await assertSucceeds(updateDoc(room(guest), {guestUid: 'guest', memberIds: ['owner','guest'], status: 'pending'}));
  await assertFails(getDoc(room(outsider)));
  await assertFails(updateDoc(room(guest), {status: 'connected'}));
  await assertSucceeds(updateDoc(room(owner), {status: 'connected'}));
  await assertSucceeds(getDocs(query(collection(guest, 'circles'), where('memberIds', 'array-contains', 'guest'))));
  await assertFails(setDoc(signal(outsider, 'outsider'), ping()));
  await assertFails(setDoc(signal(guest, 'owner'), ping()));
  await assertFails(setDoc(signal(owner, 'owner'), {kind: 'invalid', sentAt: serverTimestamp()}));
  await assertSucceeds(setDoc(signal(owner, 'owner'), ping()));
  await assertSucceeds(getDoc(signal(guest, 'owner')));
  await assertFails(getDoc(signal(outsider, 'owner')));
  await assertFails(setDoc(signal(owner, 'owner'), ping()));
  await assertFails(deleteDoc(signal(owner, 'owner')));
  await new Promise(resolve => setTimeout(resolve, 3100));
  await assertSucceeds(setDoc(signal(owner, 'owner'), {kind: 'arrival', sentAt: serverTimestamp()}));
  await assertSucceeds(updateDoc(room(guest), {status: 'closed'}));
  await assertFails(setDoc(signal(owner, 'owner'), ping()));
  await assertFails(getDoc(signal(guest, 'owner')));
  await assertFails(updateDoc(room(owner), {status: 'connected'}));
});
test('push tokens are private, owner-bound and cannot expose server delivery claims', async () => {
  const owner = env.authenticatedContext('device-owner').firestore();
  const other = env.authenticatedContext('device-other').firestore();
  const anon = env.unauthenticatedContext().firestore();
  const id = 'b'.repeat(64);
  const ref = db => doc(db, 'pushDevices', id);
  const data = () => ({ownerUid: 'device-owner', token: 'private-token'.repeat(8), platform: 'android', updatedAt: serverTimestamp()});
  await assertFails(setDoc(ref(anon), data()));
  await assertFails(setDoc(ref(other), data()));
  await assertSucceeds(setDoc(ref(owner), data()));
  await assertSucceeds(getDoc(ref(owner)));
  await assertFails(getDoc(ref(other)));
  await assertFails(getDocs(collection(other, 'pushDevices')));
  await assertFails(setDoc(ref(other), {...data(), ownerUid: 'device-other'}));
  await assertFails(updateDoc(ref(owner), {ownerUid: 'device-other'}));
  await assertFails(updateDoc(ref(owner), {platform: 'ios'}));
  await assertFails(updateDoc(ref(owner), {token: 'short'}));
  await assertFails(deleteDoc(ref(other)));
  await assertFails(setDoc(doc(owner, 'pushDeliveries', 'claim'), {claimedAt: serverTimestamp()}));
  await assertFails(getDoc(doc(owner, 'pushDeliveries', 'claim')));
  await assertSucceeds(deleteDoc(ref(owner)));
  await assertSucceeds(deleteDoc(ref(owner)));
});
